"""Generate native auth DTOs from the checked-in backend contract."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
schemas = json.loads((root / 'contracts/openapi.json').read_text())['components']['schemas']
used = {'SessionTokens':'Tokens', 'MemberView':'Member', 'ChallengeRequest':'ChallengeRequest',
        'ChallengeCreated':'Challenge', 'ChallengeProof':'Proof', 'ChallengeStatus':'ChallengeStatus',
        'RefreshRequest':'RefreshRequest'}
lines = ['// Generated by scripts/android_contract.py. Do not edit.', 'package org.vowen.app',
         'import kotlinx.serialization.Serializable', '']
for source, target in used.items():
    fields = []
    for name, prop in schemas[source]['properties'].items():
        kind = {'string':'String','boolean':'Boolean','integer':'Int'}.get(prop.get('type'))
        if kind is None:
            raise ValueError(f'Unsupported native auth field {source}.{name}')
        if name not in schemas[source]['required']:
            kind += '? = null'
        fields.append(f'val {name}: {kind}')
    lines.append('@Serializable data class '+target+'('+', '.join(fields)+')')
(root / 'android/app/src/main/java/org/vowen/app/ApiModels.kt').write_text('\n'.join(lines)+'\n')
