import {test,expect} from '@playwright/test'
import {createHmac,randomUUID} from 'node:crypto'

async function member(page:import('@playwright/test').Page,id:number) {
 const fields:Record<string,string>={auth_date:String(Math.floor(Date.now()/1000)),query_id:'forms-'+id+'-'+randomUUID(),user:JSON.stringify({id})}
 const key=createHmac('sha256','WebAppData').update('123456:synthetic_test_token_not_a_real_credential').digest()
 fields.hash=createHmac('sha256',key).update(Object.entries(fields).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>`${k}=${v}`).join('\n')).digest('hex')
 await page.route('https://telegram.org/**',r=>r.fulfill({contentType:'application/javascript',body:''}))
 await page.addInitScript(raw=>Object.assign(window,{Telegram:{WebApp:{initData:raw,ready:()=>{}}}}),new URLSearchParams(fields).toString())
 await page.goto('/')
 await page.getByRole('button',{name:'Sign in with Telegram'}).click()
}

test('visual creation, guest draft, review, receipt, reader result and withdrawal',async({page,browser})=>{
 await member(page,100000000204)
 await page.getByRole('button',{name:'New form',exact:true}).click()
 await page.getByLabel('Form title',{exact:true}).fill('Guest feedback')
 await page.getByLabel('Question 1 label',{exact:true}).fill('Your answer')
 await page.getByRole('button',{name:'Save form',exact:true}).click()
 await page.getByRole('button',{name:'Publish',exact:true}).click()
 await page.getByRole('button',{name:'Invite',exact:true}).click()
 await page.getByRole('checkbox',{name:'Reader: Demo 4',exact:true}).check()
 await page.getByRole('button',{name:'Create invitation',exact:true}).click()
 const link=await page.getByLabel('Invitation link',{exact:true}).inputValue()
 expect(link).toContain('#token=')
 const context=await browser.newContext()
 const guest=await context.newPage()
 const external:string[]=[]
 guest.on('request',r=>{if(new URL(r.url()).origin!=='http://127.0.0.1:5174')external.push(r.url())})
 await guest.goto(link.replace('https://localhost','http://127.0.0.1:5174'))
 await expect(guest.getByText('Guest feedback',{exact:true})).toHaveCount(0)
 await guest.getByRole('button',{name:'Open form',exact:true}).click()
 await expect(guest.getByText('Results readers: Demo 4')).toBeVisible()
 await guest.getByLabel('Your answer',{exact:true}).fill('Synthetic guest response')
 await guest.getByRole('button',{name:'Save draft',exact:true}).click()
 await expect(guest.getByText('Draft saved')).toBeVisible()
 await guest.reload()
 await expect(guest.getByLabel('Your answer',{exact:true})).toHaveValue('Synthetic guest response')
 await guest.getByRole('checkbox',{name:'I am 18 or older and have reviewed the readers and retention'}).check()
 await guest.getByRole('button',{name:'Review answers',exact:true}).click()
 await guest.getByRole('button',{name:'Send answers',exact:true}).click()
 await expect(guest.getByRole('heading',{name:'Response submitted',exact:true})).toBeVisible()
 await guest.getByRole('button',{name:'Create receipt',exact:true}).click()
 const receipt=await guest.getByLabel('Receipt link',{exact:true}).inputValue()
 await page.getByRole('button',{name:'Refresh forms',exact:true}).click()
 await expect(page.getByText('Synthetic guest response',{exact:true})).toBeVisible()
 const recovery=await context.newPage()
 await recovery.goto(receipt)
 await recovery.getByRole('button',{name:'Open receipt',exact:true}).click()
 // A second capability cannot silently replace the receipt, and an old tokenless
 // receipt page must not restore another invitation's response after replacement.
 await page.getByRole('button',{name:'Create invitation',exact:true}).click()
 await expect(page.getByLabel('Invitation link',{exact:true})).not.toHaveValue(link)
 const secondLink=await page.getByLabel('Invitation link',{exact:true}).inputValue()
 const otherGuest=await context.newPage()
 await otherGuest.goto(secondLink)
 await otherGuest.getByRole('button',{name:'Open form',exact:true}).click()
 await expect(otherGuest.getByRole('alertdialog',{name:'Replace guest session'})).toBeVisible()
 await otherGuest.getByRole('button',{name:'Close previous session and open link',exact:true}).click()
 await expect(otherGuest.getByLabel('Your answer',{exact:true})).toBeVisible()
 await recovery.reload()
 await expect(recovery.getByRole('alert')).toContainText('GUEST_CONTEXT_CHANGED')
 await expect(recovery.getByText('Synthetic guest response',{exact:true})).toHaveCount(0)
 await recovery.goto(receipt)
 await recovery.getByRole('button',{name:'Open receipt',exact:true}).click()
 await expect(recovery.getByRole('alertdialog',{name:'Replace guest session'})).toBeVisible()
 await recovery.getByRole('button',{name:'Close previous session and open link',exact:true}).click()
 await recovery.getByRole('button',{name:'Delete response',exact:true}).click()
 await recovery.getByRole('button',{name:'Confirm deletion',exact:true}).click()
 await expect(recovery.getByText('Response deleted')).toBeVisible()
 await page.getByRole('button',{name:'Refresh forms',exact:true}).click()
 await expect(page.getByText('Synthetic guest response',{exact:true})).toHaveCount(0)
 expect(external).toEqual([])
 await context.close()
})

