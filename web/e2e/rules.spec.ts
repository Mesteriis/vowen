import {openSection,proposeRelationship} from './workspace'
import {test,expect} from '@playwright/test'
import {createHmac,randomUUID} from 'node:crypto'
async function login(page:import('@playwright/test').Page,id:number){
 const fields:Record<string,string>={auth_date:String(Math.floor(Date.now()/1000)),query_id:'rules-'+randomUUID(),user:JSON.stringify({id})}
 const key=createHmac('sha256','WebAppData').update('123456:synthetic_test_token_not_a_real_credential').digest()
 fields.hash=createHmac('sha256',key).update(Object.entries(fields).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>`${k}=${v}`).join('\n')).digest('hex')
 await page.route('https://telegram.org/**',r=>r.fulfill({contentType:'application/javascript',body:''}))
 await page.addInitScript(raw=>Object.assign(window,{Telegram:{WebApp:{initData:raw,ready:()=>{}}}}),new URLSearchParams(fields).toString())
 await page.goto('/')
 await expect(page.locator('.startup-screen')).toHaveCount(0)
}
