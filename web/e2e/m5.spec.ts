test('permanent auth failure closes private panels and supports a fresh Telegram assertion',async({page})=>{
 await login(page,100000000212)
 await expect(page.locator('#notifications')).toBeVisible()
 await page.route('**/api/v1/me/notifications',r=>r.fulfill({status:401,contentType:'application/json',body:'{"error":{"code":"INVALID_AUTH"}}'}))
 await page.locator('#notifications').getByRole('button',{name:'Refresh notification settings',exact:true}).click()
 await expect(page.locator('#forms')).toHaveCount(0)
 await expect(page.getByText('Session ended. Close this app and reopen it through the bot to sign in again.',{exact:true})).toBeVisible()
 await page.unroute('**/api/v1/me/notifications')
 await login(page,100000000212)
 await expect(page.locator('#notifications')).toBeVisible()
})
