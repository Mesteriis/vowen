import {test,expect,type Page} from '@playwright/test'
import {createHmac,randomUUID} from 'node:crypto'
import {openSection,proposeRelationship} from './workspace'
async function login(page:Page,id:number){
 const fields:Record<string,string>={auth_date:String(Math.floor(Date.now()/1000)),query_id:'economy-'+randomUUID(),user:JSON.stringify({id})}
 const key=createHmac('sha256','WebAppData').update('123456:synthetic_test_token_not_a_real_credential').digest()
 fields.hash=createHmac('sha256',key).update(Object.entries(fields).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>`${k}=${v}`).join('\n')).digest('hex')
 await page.route('https://telegram.org/**',r=>r.fulfill({body:''}))
 await page.addInitScript(raw=>Object.assign(window,{Telegram:{WebApp:{initData:raw,ready:()=>{}}}}),new URLSearchParams(fields).toString())
 await page.goto('/')
 await expect(page.locator('.startup-screen')).toHaveCount(0)
}
test('relationship shop: grant currency with comment, buy a lot and retain history',async({page,browser})=>{
 await login(page,100000000201)
 const context=await browser.newContext({locale:'en-US'}),recipient=await context.newPage()
 await login(recipient,100000000202)
 await proposeRelationship(page)
 await page.getByRole('combobox',{name:'Participant',exact:true}).selectOption({label:'Demo 2'})
 await page.getByLabel('Agreement text',{exact:true}).fill('Synthetic shop agreement')
 await page.getByRole('checkbox',{name:'Offer rewards',exact:true}).check()
 await page.getByRole('button',{name:'Propose',exact:true}).click()
 await page.getByRole('button',{name:'Accept this exact version and scopes',exact:true}).click()
 await expect(page.getByText('Version 2 · Consents 1/2',{exact:true})).toBeVisible()
 await recipient.getByRole('button',{name:'Refresh',exact:true}).click()
 await openSection(recipient,'relations')
 await recipient.getByRole('button',{name:'Accept this exact version and scopes',exact:true}).click()
 await expect(recipient.getByText('Version 3 · Consents 2/2',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Refresh',exact:true}).click()
 await openSection(page,'rewards')
 await page.getByRole('combobox',{name:'Relationship context'}).selectOption({label:'Demo 2 · Dominant · Active'})
 await expect(page.locator('.shop-balance')).toContainText('Coins for Demo 2')
 await expect(page.getByRole('button',{name:'Buy',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'New reward',exact:true}).click()
 await page.getByLabel('Reward title',{exact:true}).fill('Movie night')
 await page.getByLabel('Reward description',{exact:true}).fill('Choose a film')
 await page.getByRole('button',{name:'Save reward',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Movie night',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Add shop item',exact:true}).click()
 await page.getByRole('combobox',{name:'Shop reward',exact:true}).selectOption({label:'Movie night'})
 await page.getByLabel('Price in coins',{exact:true}).fill('20')
 await page.getByRole('button',{name:'Save shop item',exact:true}).click()
 await expect(page.locator('.shop-item')).toContainText('20 coins')
 await page.getByRole('button',{name:'Grant coins',exact:true}).click()
 await page.getByLabel('Coin amount',{exact:true}).fill('30')
 await page.getByLabel('Credit comment',{exact:true}).fill('For your effort')
 await page.getByRole('button',{name:'Confirm credit',exact:true}).click()
 await expect(page.locator('.shop-balance strong')).toContainText('30')
 await openSection(recipient,'rewards')
 await recipient.getByRole('combobox',{name:'Relationship context'}).selectOption({label:'Demo 1 · Submissive · Active'})
 await expect(recipient.locator('.shop-balance')).toContainText('Your balance')
 await expect(recipient.getByRole('button',{name:'Grant coins',exact:true})).toHaveCount(0)
 await expect(recipient.locator('.shop-balance strong')).toContainText('30')
 await recipient.getByRole('button',{name:'Buy',exact:true}).click()
 await expect(recipient.locator('.shop-balance strong')).toContainText('10')
 await expect(recipient.locator('.reward-grant')).toContainText('Accepted')
 await recipient.getByText('Coin history',{exact:true}).click()
 await expect(recipient.locator('.currency-history')).toContainText('For your effort')
 await expect(recipient.locator('.currency-history')).toContainText('Shop purchase')
 await recipient.setViewportSize({width:390,height:844})
 expect(await recipient.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
 await recipient.screenshot({path:'test-results/shop-mobile.png'})
 await context.close()
})
