test('velvet startup artwork follows real loading and releases after failure',async({page})=>{
 let release:()=>Promise<void>=async()=>{}
 await page.route('**/api/v1/instance',route=>new Promise<void>(resolve=>{release=async()=>{await route.fulfill({status:503,contentType:'application/json',body:'{"error":{"code":"UNAVAILABLE"}}'});resolve()}}))
 await page.route('https://telegram.org/**',route=>route.fulfill({body:''}))
 await page.setViewportSize({width:390,height:844})
 await page.goto('/',{waitUntil:'domcontentloaded'})
 await expect(page.getByRole('status',{name:'Loading Vowen'})).toBeVisible()
 await expect(page.locator('.startup-screen img')).toHaveJSProperty('naturalWidth',960)
 await page.screenshot({path:'test-results/velvet-startup.png'})
 await release()
 await expect(page.getByRole('status',{name:'Loading Vowen'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Sign in with Telegram'})).toBeEnabled()
 await expect(page.locator('.app-brand img')).toHaveJSProperty('naturalWidth',384)
})
