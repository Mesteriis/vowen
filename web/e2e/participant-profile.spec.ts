 await root.getByRole('combobox',{name:'My preference',exact:true}).selectOption('conditional')
 await root.getByRole('combobox',{name:'My experience',exact:true}).selectOption('experienced')
 await root.getByRole('combobox',{name:'My participation',exact:true}).selectOption('receive')
 await root.getByLabel('Conditions & notes',{exact:true}).fill('Synthetic condition')
 for(let step=3;step<6;step++)await root.getByTestId('profile-wizard-skip').click()
 await page.setViewportSize({width:390,height:844})
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
 await page.screenshot({path:'test-results/profile-wizard-mobile.png',fullPage:true})
 await root.getByTestId('profile-publish').click()
 await expect(root.getByText('Profile saved',{exact:true})).toBeVisible()
 await expect(root.getByText('Synthetic private profile note',{exact:true})).toBeVisible()
 await expect(root.locator('.profile-overview-row').filter({hasText:'Массаж'})).toContainText('Synthetic condition')
 await root.getByRole('button',{name:'Edit profile',exact:true}).click()
 await root.getByRole('textbox',{name:'About me',exact:true}).fill('Editor to wizard survives')
 await root.getByRole('button',{name:'Use guided setup',exact:true}).click()
 for(let step=1;step<6;step++)await root.getByTestId('profile-wizard-skip').click()
 await root.getByTestId('profile-publish').click()
 await expect(root.getByText('Editor to wizard survives',{exact:true})).toBeVisible()
 await root.getByRole('button',{name:'Edit profile',exact:true}).click()
 await root.getByRole('textbox',{name:'About me',exact:true}).fill('Snapshot is protected while saving')
 let release!:()=>void
 const gate=new Promise<void>(resolve=>{release=resolve})
 await page.route('**/api/v1/me/profile/draft',async route=>{if(route.request().method()==='PUT')await gate;await route.continue()},{times:1})
 await root.getByRole('button',{name:'Save profile',exact:true}).click()
